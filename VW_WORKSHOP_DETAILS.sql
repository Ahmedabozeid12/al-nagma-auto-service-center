CREATE OR REPLACE VIEW VW_WORKSHOP_DETAILS AS
SELECT
    JCS.JOB_CARD_SERVICE_ID,
    JCS.JOB_CARD_ID,
    S.SERVICE_NAME,
    T.FULL_NAME AS TECHNICIAN_NAME,
    JCS.QUANTITY,
    JCS.UNIT_PRICE,
    JCS.LINE_STATUS
FROM JOB_CARD_SERVICES JCS,
     SERVICES S,
     TECHNICIANS T
WHERE JCS.SERVICE_ID = S.SERVICE_ID
  AND JCS.TECHNICIAN_ID = T.TECHNICIAN_ID;