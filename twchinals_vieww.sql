
CREATE OR REPLACE VIEW VW_WORKSHOP_CARDS AS
SELECT
    JC.JOB_CARD_ID,
    JC.OPEN_DATE,
    JC.EXPECTED_DELIVERY,
    JC.STATUS_ID,
    JS.STATUS_NAME,
    JC.CARD_TYPE,
    JC.CUSTOMER_COMPLAINT,
    V.PLATE_NUMBER,
    V.MAKE,
    V.MODEL
FROM JOB_CARDS JC,
     JOB_STATUS JS,
     VEHICLES V
WHERE JC.STATUS_ID = JS.STATUS_ID
  AND JC.VEHICLE_ID = V.VEHICLE_ID
  AND JC.STATUS_ID NOT IN (7, 8);