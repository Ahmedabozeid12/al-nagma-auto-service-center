CREATE OR REPLACE TRIGGER HE.TRG_RECEIPT_ITEM_STOCK
AFTER INSERT ON HE.RECEIPT_ITEMS
FOR EACH ROW
BEGIN
    UPDATE HE.PARTS
       SET QUANTITY_ON_HAND =
           QUANTITY_ON_HAND + :NEW.QUANTITY
     WHERE PART_ID = :NEW.PART_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20310,
            'Part not found for this receipt item.'
        );
    END IF;
END;
/