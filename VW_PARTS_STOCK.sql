
CREATE OR REPLACE VIEW VW_PARTS_STOCK AS
SELECT
    PART_ID,
    PART_CODE,
    PART_NAME,
    CATEGORY,
    UNIT,
    QUANTITY_ON_HAND,
    REORDER_LEVEL,
    CASE
        WHEN QUANTITY_ON_HAND = 0 THEN 'OUT_OF_STOCK'
        WHEN QUANTITY_ON_HAND <= REORDER_LEVEL THEN 'LOW_STOCK'
        ELSE 'AVAILABLE'
    END AS STOCK_STATUS
FROM PARTS;
