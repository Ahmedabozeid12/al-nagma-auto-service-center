CREATE OR REPLACE VIEW V_VEHICLE_HISTORY AS
SELECT
    J.JOB_CARD_ID,
    V.VEHICLE_ID,
    V.PLATE_NUMBER,
    C.FULL_NAME,
    V.MAKE,
    V.MODEL,
    V.COLOR,
    J.OPEN_DATE,
    J.CLOSE_DATE,
    S.STATUS_NAME,
    J.CUSTOMER_COMPLAINT,
    J.ODOMETER_READING,
    J.EXPECTED_DELIVERY
FROM JOB_CARDS J,
     VEHICLES V,
     CUSTOMERS C,
     JOB_STATUS S
WHERE J.VEHICLE_ID = V.VEHICLE_ID
AND V.CUSTOMER_ID = C.CUSTOMER_ID
AND J.STATUS_ID = S.STATUS_ID;