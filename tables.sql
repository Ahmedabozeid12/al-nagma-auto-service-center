-- =====================================================================
-- hr_00_tables_full.sql
-- ONE script that creates every table (final shape, with all changes),
-- its sequence and trigger, plus the reference data.
-- Connect as HR and run as a script (F5).  Oracle 12c+ (STANDARD_HASH).
--
-- Use this ONLY for a fresh start.  If your tables already exist, run
-- hr_01_alter_tables.sql instead (it changes them in place, keeps your data).
--
-- To start from zero, first run the DROP block at the bottom of this file
-- (it is commented out - it deletes ALL data).
--
-- Names kept from your code: CUSTOMER_ID_SEQ, CUSTOMER_ID_TRG, RECEIPT_SEQ,
-- RECEIPT_ITEM_SEQ, PARTS_ISSUED_SEQ, PAYMENT_SEQ, CAR_WASH_SEQ, INVOICE_SEQ,
-- INVOICE_ITEM_SEQ (the packages use them).  Renamed only to remove confusion:
-- triggers that had the same name as their sequence (USER_SEQ, JOB_CARD_SEQ,
-- SERVISE_SEQ) are now USERS_BI, JOB_CARDS_BI, SERVICES_BI.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Password hash function (used by login and by the user screen)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION HASH_PWD
(
    P_USERNAME VARCHAR2,
    P_PASSWORD VARCHAR2
) RETURN VARCHAR2 DETERMINISTIC
IS
BEGIN
    RETURN LOWER(RAWTOHEX(STANDARD_HASH(LOWER(P_USERNAME) || ':' || P_PASSWORD, 'SHA256')));
END;
/


